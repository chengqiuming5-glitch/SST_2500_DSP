/***********************************************************************************************
* @Type         : Module function
* @brief        : CPU Timer Initial function
* @Signal [in]  : null
* @Signal [out] : null
* @return       : null
***********************************************************************************************/
void v_TmrCfg_Init(void)
{
    InitCpuTimers();                                ///< Initialize all three CPU timers
    ConfigCpuTimer(&CpuTimer0, 200.0f, 1000.0f);    ///< Configure CpuTimer0 Period to 1ms
    StopCpuTimer0();                                ///< Stop CpuTimer0

#if 1U == FLG_RUN_TIME_TEST_EN
    ConfigCpuTimer(&CpuTimer1, 200.0f, (float32)PERD_CPUTIMER1);      ///< Configure CpuTimer1 Period to 20us
    StopCpuTimer1();                                                  ///< Stop CpuTimer1
#endif
}

